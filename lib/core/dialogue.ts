export type DialogueResult = {
  answer: string;
  intent: string;
};

type DialoguePattern = {
  intent: string;
  patterns: RegExp[];
  respond: (text: string, previousUserMessage?: string) => string;
};

const PATTERNS: DialoguePattern[] = [
  {
    intent: "wellbeing",
    patterns: [/^(how are you|how are you doing|you alright|are you okay)[.!? ]*$/],
    respond: () => "I'm running and ready to help. What would you like to work on?",
  },
  {
    intent: "identity",
    patterns: [/^(who are you|what is your name|what should i call you|are you a robot|are you an ai)[.!? ]*$/],
    respond: () => "I'm Chatty AI. My answers are generated by Chatty Core, this project's own programmed reasoning and knowledge system. I don't rely on a hosted language model to answer your messages.",
  },
  {
    intent: "creator",
    patterns: [/^(who created you|who made you|who built you)[.!? ]*$/],
    respond: () => "Chatty AI is being developed as an independent project. Its reasoning modules, knowledge base and conversation rules are written into this codebase.",
  },
  {
    intent: "greeting",
    patterns: [/^(hi|hello|hey|hiya|good morning|good afternoon|good evening|howdy)[.!? ]*$/],
    respond: (text) => {
      const lower = text.toLowerCase();
      if (lower.includes("morning")) return "Good morning! What are we working on today?";
      if (lower.includes("afternoon")) return "Good afternoon! What would you like to explore?";
      if (lower.includes("evening")) return "Good evening! What can I help you work through?";
      return "Hello! What would you like to talk about or solve?";
    },
  },
  {
    intent: "gratitude",
    patterns: [/^(thanks|thank you|thanks a lot|cheers|much appreciated)[.!? ]*$/],
    respond: () => "You're welcome. What would you like to look at next?",
  },
  {
    intent: "goodbye",
    patterns: [/^(bye|goodbye|see you|see ya|talk later|i have to go)[.!? ]*$/],
    respond: () => "Goodbye. Your conversation is saved in this browser, so you can return to it later.",
  },
  {
    intent: "apology",
    patterns: [/^(sorry|my apologies|i am sorry)[.!? ]*$/],
    respond: () => "No problem. We can take another approach. Tell me what you would like to change.",
  },
  {
    intent: "correction",
    patterns: [/^(you are wrong|that's wrong|that is wrong|incorrect|not correct|you made a mistake)[.!? ]*$/],
    respond: () => "Thanks for pointing that out. Tell me which part you believe is incorrect, and I'll check it against the rules and information available to me.",
  },
  {
    intent: "confusion",
    patterns: [/^(i don't understand|i do not understand|i'm confused|im confused|that makes no sense)[.!? ]*$/],
    respond: (_text, previous) => previous
      ? "Let's approach it more simply. You were asking about: " + previous + ". I'll break the idea into smaller steps."
      : "Let's take it one step at a time. Which word or part is confusing?",
  },
  {
    intent: "encouragement",
    patterns: [/^(i can do this|i will do it|i got this|i can learn this)[.!? ]*$/],
    respond: () => "Keep going one step at a time. Practice, check your mistakes and build on what you understand.",
  },
];

export function matchDialogue(text: string, previousUserMessage?: string): DialogueResult | null {
  const clean = text.trim();
  if (!clean || clean.length > 180) return null;

  for (const item of PATTERNS) {
    if (item.patterns.some((pattern) => pattern.test(clean))) {
      return { intent: item.intent, answer: item.respond(clean, previousUserMessage) };
    }
  }

  return null;
}

export function dialogueIntentCount(): number {
  return PATTERNS.length;
}
